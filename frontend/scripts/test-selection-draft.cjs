const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const source = fs.readFileSync(path.join(__dirname, '../src/lib/selectionDraft.ts'), 'utf8');
const output = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const saved = new Map();
const context = { exports: {}, localStorage: { getItem: key => saved.get(key) ?? null } };
vm.runInNewContext(output, context);
const { selectionDraftKey: key, readSelectionDraft: read } = context.exports;
const original = '整章原稿。'.repeat(1000);
const k = key('book-a', 'chapter', original);
assert.notEqual(k, key('book-b', 'chapter', original));
assert.notEqual(k, key('book-a', 'outline', original));
saved.set(k, JSON.stringify({ selection: original, instruction: '修改意见'.repeat(1000), feedback: '下一轮意见', candidate: '修改后的整章', attempts: [{ text: '上一稿', feedback: '第一轮' }] }));
assert.equal(read(k, original).instruction, '修改意见'.repeat(1000));
assert.equal(read(k, original).candidate, '修改后的整章');
assert.equal(read(k, original).feedback, '下一轮意见');
assert.equal(read(k, original).attempts[0].text, '上一稿');
assert.equal(read(k, '另一份原稿').instruction, '');
saved.set(k, JSON.stringify({ selection: original, instruction: '旧版意见', feedback: '旧版追问' }));
assert.equal(read(k, original).instruction, '旧版意见');
assert.equal(read(k, original).candidate, '');
saved.set(k, JSON.stringify({ selection: original, attempts: [null, {}, { text: '稿', feedback: '意见' }] }));
assert.equal(read(k, original).attempts.length, 1);
saved.set(k, '{broken');
assert.equal(read(k, original).instruction, '');
console.log('Draft restoration, long instructions, book isolation, legacy and corrupt data: passed.');
